#!/bin/bash
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
COMPOSE_DIR="${ROOT_DIR}/docker"
OVERRIDE_FILE="${COMPOSE_DIR}/docker-compose.override.yml"

DOCKER_BIN="${DOCKER_BIN:-docker}"
REQUESTED_MODE="${SIM_DISPLAY_MODE:-${1:-auto}}"

echo "==============================================================="
echo "  Hardware & Display Environment Detection"
echo "==============================================================="

# 1. Check Docker availability
if ! command -v "$DOCKER_BIN" &> /dev/null; then
    echo "[!] Error: Docker CLI not found. Please install Docker."
    exit 1
fi

# 2. Check for WSLg (Windows 11 / WSL2 native GUI & GPU bridge)
HAS_WSLG=false
if [ -e "/dev/dxg" ] && { [ -d "/mnt/wslg" ] || [ -S "/tmp/.X11-unix/X0" ]; }; then
    HAS_WSLG=true
fi

# 3. Check for Native Linux X11 display
HAS_LINUX_X11=false
if [ "$HAS_WSLG" = false ] && [ -n "$DISPLAY" ] && [ -d "/tmp/.X11-unix" ]; then
    HAS_LINUX_X11=true
fi

# 4. Check for DRI (Intel/AMD GPU)
HAS_DRI=false
if [ -d "/dev/dri" ]; then
    HAS_DRI=true
fi

# 5. Check for NVIDIA GPU support via Docker
HAS_NVIDIA=false
if $DOCKER_BIN info 2>/dev/null | grep -iE 'nvidia|runtimes:.*nvidia' >/dev/null 2>&1 || \
   timeout 4 $DOCKER_BIN run --rm --gpus all ubuntu:22.04 true >/dev/null 2>&1; then
    HAS_NVIDIA=true
fi

# Determine Mode
DETECTED_MODE="novnc"

if [ "$REQUESTED_MODE" = "novnc" ]; then
    echo "[*] User override requested: Forcing noVNC web browser interface."
    DETECTED_MODE="novnc"
elif [ "$REQUESTED_MODE" = "wslg" ] || { [ "$REQUESTED_MODE" = "auto" ] && [ "$HAS_WSLG" = true ] && [ "$HAS_NVIDIA" = true ]; }; then
    DETECTED_MODE="wslg_nvidia"
elif [ "$HAS_WSLG" = true ]; then
    DETECTED_MODE="wslg_basic"
elif [ "$HAS_LINUX_X11" = true ] && [ "$HAS_NVIDIA" = true ]; then
    DETECTED_MODE="linux_nvidia"
elif [ "$HAS_LINUX_X11" = true ] && [ "$HAS_DRI" = true ]; then
    DETECTED_MODE="linux_dri"
elif [ "$HAS_LINUX_X11" = true ]; then
    DETECTED_MODE="linux_x11"
else
    DETECTED_MODE="novnc"
fi

echo "[*] Hardware Probing Results:"
echo "    - NVIDIA GPU via Docker : $( [ "$HAS_NVIDIA" = true ] && echo 'Detected (RTX/GTX)' || echo 'None / Not active' )"
echo "    - Windows WSLg Display  : $( [ "$HAS_WSLG" = true ] && echo 'Available' || echo 'No' )"
echo "    - Linux Native X11      : $( [ "$HAS_LINUX_X11" = true ] && echo "Available (Display $DISPLAY)" || echo 'No' )"
echo "    - DRI Acceleration      : $( [ "$HAS_DRI" = true ] && echo 'Available' || echo 'No' )"
echo "---------------------------------------------------------------"

case "$DETECTED_MODE" in
    wslg_nvidia)
        echo "[+] ACTIVATED: Windows WSLg with NVIDIA GPU Hardware Acceleration"
        echo "    Gazebo & RViz will open as native desktop windows at 60 FPS."
        cat << 'EOF' > "$OVERRIDE_FILE"
# Auto-generated by scripts/detect_hardware.sh
# Mode: WSLg with NVIDIA GPU Acceleration
services:
  ros2_sim:
    environment:
      - DISPLAY=:0
      - WAYLAND_DISPLAY=wayland-0
      - XDG_RUNTIME_DIR=/mnt/wslg/runtime-dir
      - PULSE_SERVER=/mnt/wslg/PulseServer
      - LD_LIBRARY_PATH=/usr/lib/wsl/lib
      - LIBGL_ALWAYS_SOFTWARE=0
      - USE_HOST_DISPLAY=1
      - NVIDIA_VISIBLE_DEVICES=all
      - NVIDIA_DRIVER_CAPABILITIES=all
    volumes:
      - /tmp/.X11-unix:/tmp/.X11-unix:rw
      - /mnt/wslg:/mnt/wslg:rw
      - /usr/lib/wsl/lib:/usr/lib/wsl/lib:ro
    devices:
      - /dev/dxg:/dev/dxg
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              count: all
              capabilities: [gpu, graphics, display]
EOF
        ;;

    wslg_basic)
        echo "[+] ACTIVATED: Windows WSLg (Direct Desktop Window Display)"
        echo "    Gazebo & RViz will open as native desktop windows."
        cat << 'EOF' > "$OVERRIDE_FILE"
# Auto-generated by scripts/detect_hardware.sh
# Mode: WSLg Direct Desktop Display
services:
  ros2_sim:
    environment:
      - DISPLAY=:0
      - WAYLAND_DISPLAY=wayland-0
      - XDG_RUNTIME_DIR=/mnt/wslg/runtime-dir
      - PULSE_SERVER=/mnt/wslg/PulseServer
      - USE_HOST_DISPLAY=1
    volumes:
      - /tmp/.X11-unix:/tmp/.X11-unix:rw
      - /mnt/wslg:/mnt/wslg:rw
    devices:
      - /dev/dxg:/dev/dxg
EOF
        ;;

    linux_nvidia)
        echo "[+] ACTIVATED: Native Linux X11 with NVIDIA GPU Acceleration"
        cat << EOF > "$OVERRIDE_FILE"
# Auto-generated by scripts/detect_hardware.sh
# Mode: Native Linux with NVIDIA GPU Acceleration
services:
  ros2_sim:
    environment:
      - DISPLAY=${DISPLAY:-:0}
      - USE_HOST_DISPLAY=1
      - NVIDIA_VISIBLE_DEVICES=all
      - NVIDIA_DRIVER_CAPABILITIES=all
    volumes:
      - /tmp/.X11-unix:/tmp/.X11-unix:rw
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              count: all
              capabilities: [gpu, graphics, display]
EOF
        ;;

    linux_dri)
        echo "[+] ACTIVATED: Native Linux X11 with Intel/AMD DRI Acceleration"
        cat << EOF > "$OVERRIDE_FILE"
# Auto-generated by scripts/detect_hardware.sh
# Mode: Native Linux with DRI Acceleration
services:
  ros2_sim:
    environment:
      - DISPLAY=${DISPLAY:-:0}
      - USE_HOST_DISPLAY=1
    volumes:
      - /tmp/.X11-unix:/tmp/.X11-unix:rw
    devices:
      - /dev/dri:/dev/dri
EOF
        ;;

    linux_x11)
        echo "[+] ACTIVATED: Native Linux X11 Display"
        cat << EOF > "$OVERRIDE_FILE"
# Auto-generated by scripts/detect_hardware.sh
# Mode: Native Linux X11
services:
  ros2_sim:
    environment:
      - DISPLAY=${DISPLAY:-:0}
      - USE_HOST_DISPLAY=1
    volumes:
      - /tmp/.X11-unix:/tmp/.X11-unix:rw
EOF
        ;;

    *)
        echo "[+] ACTIVATED: Universal Fallback (noVNC Browser Interface)"
        echo "    Open http://localhost:6080/vnc.html in your browser after launch."
        cat << 'EOF' > "$OVERRIDE_FILE"
# Auto-generated by scripts/detect_hardware.sh
# Mode: Universal Fallback (noVNC Web Browser)
services:
  ros2_sim:
    environment:
      - DISPLAY=:1
      - USE_HOST_DISPLAY=0
EOF
        ;;
esac

echo "==============================================================="
echo "Config written to: docker/docker-compose.override.yml"
echo "==============================================================="
